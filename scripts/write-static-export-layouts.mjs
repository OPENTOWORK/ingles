/**
 * Genera `layout.js` con `generateStaticParams` en cada segmento dinámico `[part]`
 * para que `next build` con `output: 'export'` pueda pre-renderizar esas rutas.
 * Ejecutado desde `prebuild` en package.json.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.join(__dirname, '..', 'src', 'app');

function partRangeForDir(dirPath) {
  const norm = dirPath.replace(/\\/g, '/');
  if (norm.includes('/exam-1/')) return 24;
  if (norm.includes('/writing/')) return 2;
  return 8;
}

const CEFR_VALUES = ['a2', 'b1', 'b2', 'c1', 'c2'];

function partLayoutSource(range) {
  const nums = Array.from({ length: range }, (_, i) => i + 1);
  return `// Auto-generated by scripts/write-static-export-layouts.mjs — no editar a mano

export function generateStaticParams() {
  return [${nums.map((n) => `'${n}'`).join(', ')}].map((part) => ({ part }));
}

export default function StaticExportPartLayout({ children }) {
  return children;
}
`;
}

function cefrLayoutSource(values) {
  return `// Auto-generated by scripts/write-static-export-layouts.mjs — no editar a mano

export function generateStaticParams() {
  return [${values.map((v) => `'${v}'`).join(', ')}].map((cefr) => ({ cefr }));
}

export default function StaticExportCefrLayout({ children }) {
  return children;
}
`;
}

function walk(dir, out = []) {
  for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, name.name);
    if (name.isDirectory()) {
      if (name.name === '[part]' || name.name === '[cefr]') out.push(full);
      walk(full, out);
    }
  }
  return out;
}

const dirs = walk(appDir);

let partCount = 0;
let cefrCount = 0;
for (const dir of dirs) {
  const leaf = path.basename(dir);
  if (leaf === '[part]') {
    const range = partRangeForDir(dir);
    fs.writeFileSync(path.join(dir, 'layout.js'), partLayoutSource(range), 'utf8');
    partCount += 1;
  } else if (leaf === '[cefr]') {
    fs.writeFileSync(path.join(dir, 'layout.js'), cefrLayoutSource(CEFR_VALUES), 'utf8');
    cefrCount += 1;
  }
}

console.log(
  `write-static-export-layouts: wrote ${partCount} [part]/layout.js and ${cefrCount} [cefr]/layout.js files`,
);
