import { choice, exercise, gap, intention, order, transform, trueFalse } from './b2TrainingItemBuilders.js';

function level(number, title, category, focus, items) {
  const id = `b2-basic-${String(number).padStart(2, '0')}`;
  const point = title.charAt(0).toLowerCase() + title.slice(1);
  return exercise({
    id,
    category,
    focus,
    title,
    point,
    items: items.map((item, index) => ({
      ...item,
      itemId: `${id}-q${String(index + 1).padStart(2, '0')}`,
    })),
  });
}

