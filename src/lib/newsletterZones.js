/** @returns {string} zona de la lista, o cadena vacía si no viene o no es válida */
export function normalizeNewsletterZone(value) {
  const zone = String(value || '').trim();
  if (!zone || /[\r\n\0]/.test(zone)) return '';
  return NEWSLETTER_ZONES.includes(zone) ? zone : '';
}
