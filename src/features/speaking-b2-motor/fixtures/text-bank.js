function enrichTextCase(item) {
  if (!item) return null;
  return {
    ...item,
    referenceTranscript: item.referenceTranscript || item.candidateText,
    pedagogicalNotes: item.notes || '',
  };
}

export function listSpeakingB2TextCases(set = 'validate') {
  return SPEAKING_B2_TEXT_CASES.filter((item) => item.set === set).map(enrichTextCase);
}

export function getSpeakingB2TextCase(id) {
  return enrichTextCase(SPEAKING_B2_TEXT_CASES.find((item) => item.id === id) || null);
}
